"""Copy the ready guides into the frontend mock, so mock mode answers area/developer questions.

The browser cannot read data/docs, so this writes frontend/lib/mock/guides.ts from the same
chunks the real RAG uses (one entry per section, with its source). Run it again after editing
a guide:

    python scripts/build_mock_guides.py

Payment-plan sections are left out on purpose: in the chat, numbers come from the calculator.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.rag.docs import chunk_doc, load_docs

DOCS = ROOT / "data" / "docs"
OUT = ROOT / "frontend" / "lib" / "mock" / "guides.ts"
SKIP_HEADINGS = ("خطط السداد",)
LINK = re.compile(r"\[([^\]]+)\]\((https?://[^)\s]+)\)")


def plain(text: str) -> str:
    """Section text without the markdown links (the link becomes the chip)."""
    text = LINK.sub("", text)
    lines = [re.sub(r"\s+", " ", ln).strip() for ln in text.splitlines()]
    return " ".join(ln for ln in lines if ln).replace(" .", ".").strip()


def main() -> int:
    docs, problems = load_docs(DOCS)
    for p in problems:
        print("problem:", p)
    entries = []
    for doc in docs:
        for c in chunk_doc(doc):
            if c.heading.startswith(SKIP_HEADINGS):
                continue
            entries.append(
                {
                    "entity_id": c.entity_id,
                    "doc_type": c.doc_type,
                    "title": c.title,
                    "heading": c.heading,
                    "text": plain(c.text),
                    "source": {"title": c.source_title, "url": c.source_url},
                }
            )
    body = json.dumps(entries, ensure_ascii=False, indent=2)
    OUT.write_text(
        "// GENERATED by scripts/build_mock_guides.py from data/docs. Do not edit by hand.\n"
        'import type { SourceRef } from "@/lib/types";\n\n'
        "export interface GuideSection {\n"
        "  entity_id: string;\n"
        '  doc_type: "area_guide" | "developer_profile";\n'
        "  title: string;\n"
        "  heading: string;\n"
        "  text: string;\n"
        "  source: SourceRef;\n"
        "}\n\n"
        f"export const GUIDE_SECTIONS: GuideSection[] = {body};\n",
        encoding="utf-8",
    )
    print(f"wrote {len(entries)} sections from {len(docs)} guides to {OUT.relative_to(ROOT)}")
    return 0 if not problems else 1


if __name__ == "__main__":
    raise SystemExit(main())
